const uint8_t* fontGlyph(char c) {
  if (c >= 'a' && c <= 'z') c = char(c - 'a' + 'A');
  for (const Glyph& g : kGlyphs) {
    if (g.ch == c) return g.rows;
  }
  return kMissing;
}

int fontTextWidth(const std::string& text, int scale, int spacing) {
  if (text.empty()) return 0;
  return int(text.size()) * fontAdvance(scale, spacing) - spacing * scale;
}

void fontDraw(Framebuffer& fb, int x, int y, const std::string& text, RGBA color, int scale,
              int spacing) {
  if (scale < 1) scale = 1;
  int penX = x;
  for (char c : text) {
    if (c != ' ') {
      const uint8_t* rows = fontGlyph(c);
      for (int gy = 0; gy < kGlyphH; ++gy) {
        const uint8_t bits = rows[gy];
        if (!bits) continue;
        for (int gx = 0; gx < kGlyphW; ++gx) {
          if ((bits >> (kGlyphW - 1 - gx)) & 1) {
            fb.fillRect(penX + gx * scale, y + gy * scale, scale, scale, color);
          }
        }
      }
    }
    penX += fontAdvance(scale, spacing);
  }
}

void fontDrawOutlined(Framebuffer& fb, int x, int y, const std::string& text, RGBA color,
                      RGBA outline, int scale, int spacing) {
  const int o = scale;
  for (int dy = -1; dy <= 1; ++dy) {
    for (int dx = -1; dx <= 1; ++dx) {
      if (dx == 0 && dy == 0) continue;
      fontDraw(fb, x + dx * o, y + dy * o, text, outline, scale, spacing);
    }
  }
  fontDraw(fb, x, y, text, color, scale, spacing);
}

void fontDrawCentered(Framebuffer& fb, int x, int y, int width, const std::string& text, RGBA color,
                      int scale, int spacing) {
  const int tw = fontTextWidth(text, scale, spacing);
  fontDraw(fb, x + (width - tw) / 2, y, text, color, scale, spacing);
}

void fontDrawTexture(Texture& tex, int x, int y, const std::string& text, RGBA color, int scale,
                     int spacing) {
  if (scale < 1) scale = 1;
  int penX = x;
  for (char c : text) {
    if (c != ' ') {
      const uint8_t* rows = fontGlyph(c);
      for (int gy = 0; gy < kGlyphH; ++gy) {
        const uint8_t bits = rows[gy];
        if (!bits) continue;
        for (int gx = 0; gx < kGlyphW; ++gx) {
          if ((bits >> (kGlyphW - 1 - gx)) & 1) {
            for (int sy = 0; sy < scale; ++sy)
              for (int sx = 0; sx < scale; ++sx)
                setTexel(tex, penX + gx * scale + sx, y + gy * scale + sy, color);
          }
        }
      }
    }
    penX += fontAdvance(scale, spacing);
  }
}

